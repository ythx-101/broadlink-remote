"""Send TCL AC IR codes based on Opus analysis"""
import struct, sys

MARK = 131
ZERO_SPACE = 82
ONE_SPACE = 279
HEADER_MARK = 795
HEADER_SPACE = 418
GAP1 = 18178
GAP2 = 27304

def bytes_to_pulses(data_bytes):
    pulses = [HEADER_MARK, HEADER_SPACE]
    for byte in data_bytes:
        for bit_idx in range(8):
            bit = (byte >> bit_idx) & 1
            pulses.append(MARK)
            pulses.append(ONE_SPACE if bit else ZERO_SPACE)
    return pulses

def encode_broadlink(pulses_us):
    encoded = []
    for p in pulses_us:
        ticks = round(p / 8.192)
        if ticks > 255:
            encoded.extend([0, (ticks >> 8) & 0xFF, ticks & 0xFF])
        else:
            encoded.append(max(1, ticks))
    payload = bytes(encoded)
    header = struct.pack('<BBH', 0x26, 0x00, len(payload))
    return header + payload

def make_packet(f1, f2):
    if f1:
        pulses = bytes_to_pulses(f1) + [MARK, GAP1] + bytes_to_pulses(f2) + [MARK, GAP2]
    else:
        pulses = bytes_to_pulses(f2) + [MARK, GAP2]
    return encode_broadlink(pulses).hex()

